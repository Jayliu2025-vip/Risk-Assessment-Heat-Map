def sample_risks():
    rows = []
    for rid, name, dom, desc, dept, per in _BASE:
        for p, sc in ((P1, per[P1]), (P2, per[P2])):
            rows.append({
                "risk_id": rid, "name": name, "domain": dom,
                "description": desc, "owner_dept": dept, "period": p,
                "likelihood": sc[0],
                "imp_financial": sc[1], "imp_compliance": sc[2],
                "imp_operation": sc[3], "imp_reputation": sc[4],
                "imp_fraud": sc[5], "rationale": _BASIS[rid],
            })
    return rows


def sample_controls():
    rows, seq = [], 0
    for p in (P2, P1):
        mapping = _CONTROLS_26 if p == P2 else {}
        for rid, lst in mapping.items():
            for desc, score, key in lst:
                seq += 1
                rows.append({"control_id": f"C{seq:03d}", "risk_id": rid,
                             "period": p, "description": desc, "score": score,
                             "key": key})
    for rid, (desc, score) in _CONTROLS_25_DESC.items():
        seq += 1
        rows.append({"control_id": f"C{seq:03d}", "risk_id": rid,
                     "period": P1, "description": desc, "score": score,
                     "key": "是"})
    return rows


def dump_all():
    """生成 data/export/{期间}/ 的 CSV 对与根 config.json，以及前端内置数据 web/sample_data.js"""
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    risks, controls = sample_risks(), sample_controls()
    cfg = json.loads(json.dumps(DEFAULT_CONFIG))

    for p in (P1, P2):
        d = os.path.join(root, "data", "export", p)
        os.makedirs(d, exist_ok=True)
        with open(os.path.join(d, "risks.csv"), "w", newline="", encoding="utf-8-sig") as f:
            w = csv.DictWriter(f, fieldnames=RISK_FIELDS)
            w.writeheader()
            w.writerows([r for r in risks if r["period"] == p])
        with open(os.path.join(d, "controls.csv"), "w", newline="", encoding="utf-8-sig") as f:
            w = csv.DictWriter(f, fieldnames=CONTROL_FIELDS)
            w.writeheader()
            w.writerows([c for c in controls if c["period"] == p])
    with open(os.path.join(root, "data", "export", "config.json"), "w", encoding="utf-8") as f:
        json.dump(cfg, f, ensure_ascii=False, indent=2)

    web_dir = os.path.join(root, "web")
    os.makedirs(web_dir, exist_ok=True)
    payload = {"config": cfg,
               "periods": {p: {"risks": [r for r in risks if r["period"] == p],
                               "controls": [c for c in controls if c["period"] == p]}
                           for p in (P1, P2)}}
    with open(os.path.join(web_dir, "sample_data.js"), "w", encoding="utf-8") as f:
        f.write("window.SAMPLE_DATA = ")
        f.write(json.dumps(payload, ensure_ascii=False))
        f.write(";\n")
    print(f"risks={len(risks)} controls={len(controls)} -> data/export/*, web/sample_data.js")


if __name__ == "__main__":
    dump_all()
